    let translationsEnLoading = null;
    function ensureTranslations(lang) {
      if (lang !== "en" || translations.en) {
        return Promise.resolve();
      }
      if (translationsEnLoading) {
        return translationsEnLoading;
      }
      translationsEnLoading = new Promise((resolve, reject) => {
        const script = document.createElement("script");
        script.src = "/config-i18n-en.js";
        script.onload = () => {
          translationsEnLoading = null;
          resolve();
        };
        script.onerror = () => {
          translationsEnLoading = null;
          reject(new Error("i18n_en_load_failed"));
        };
        document.head.appendChild(script);
      });
      return translationsEnLoading;
    }
